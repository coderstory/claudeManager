//! McpServer — domain model (M2.5, F6).
//!
//! SPEC §2.1 is the contract; this module owns the Rust representation.
//! The on-disk shape is `~/.claude/mcp.json` (single file, with
//! `mcpServers` as a name → server map) — see SPEC §2.2 and the F6
//! dataflow in `docs/design/M2.5-dataflow.md`.
//!
//! ## Conventions
//!
//! - **Disk shape ≠ struct shape.** On disk: `{"mcpServers": {"name":
//!   {...}}}`. In the service layer: `Vec<McpServer>` with `name` as
//!   a field, plus a uuid `id` for stable list/toggle keys. The
//!   service owns the disk ↔ struct translation; the domain model
//!   only deals with the struct.
//! - `enabled` defaults to `true` if missing on disk — matches Claude
//!   Code's own default behaviour (a server entry without a
//!   disabled flag is enabled).
//! - `id` is generated client-side (`uuid::Uuid::new_v4().to_string()`)
//!   and is NEVER part of the on-disk map key. The map key is `name`.
//! - `transport` is the discriminant: `stdio` uses `command` + `args`
//!   + `env`; `http` uses `url`. Cross-validation lives in
//!   [`McpServer::validate`].
//!
//! ## Why a fresh struct (not reuse `infrastructure::sql_parser::McpServer`)
//!
//! The F3 SQL parser produces a *parser-shaped* McpServer: id +
//! name + command + args + env + description. F6's write-side
//! needs *more*: transport + enabled + created_at + uuid. Two
//! types, two responsibilities. The service translates between
//! them when bridging a SQL-imported entry to a writeable entry.

use std::collections::HashMap;
use std::path::Path;

use serde::{Deserialize, Serialize};
use thiserror::Error;

use crate::domain::is_valid_id;

/// One MCP server entry the user manages from the F6 page.
///
/// Field naming follows the Rust convention `snake_case`; serde's
/// `rename_all` keeps the JSON shape identical for the frontend
/// mirror in `src/types/mcp.ts`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct McpServer {
    /// UUID — stable list/toggle key. Never part of the on-disk
    /// `mcpServers` map key (that is `name`). Generated by
    /// [`McpServer::new`] with `uuid::Uuid::new_v4()`.
    pub id: String,

    /// Display name; ALSO the on-disk map key. Must be non-empty
    /// (validated in [`McpServer::validate`]).
    pub name: String,

    /// Transport discriminant. `Stdio` = `command` + `args` + `env`
    /// are meaningful; `Http` = `url` is meaningful. Validation
    /// enforces that the corresponding fields are populated.
    pub transport: McpTransport,

    /// Stdio transport only — the executable to run (e.g. `npx`).
    /// Ignored (and should be `None`) for Http transport.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub command: Option<String>,

    /// Stdio transport only — CLI args passed to `command`.
    #[serde(default)]
    pub args: Vec<String>,

    /// Stdio transport only — env vars set when launching.
    #[serde(default)]
    pub env: HashMap<String, String>,

    /// Http transport only — the SSE / streamable-http endpoint URL.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,

    /// Whether the server is enabled. Defaults to `true` when
    /// missing on disk.
    #[serde(default = "default_enabled")]
    pub enabled: bool,

    /// Unix seconds (matches `Provider::created_at` convention).
    pub created_at: i64,
}

fn default_enabled() -> bool {
    true
}

/// Transport discriminant for an MCP server entry. The on-disk
/// `server_config` JSON uses `{"type": "stdio", ...}` or
/// `{"type": "http", ...}` (Claude Code's own format).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "lowercase")]
pub enum McpTransport {
    /// Subprocess transport: `command` + `args` + `env`.
    Stdio,
    /// HTTP / SSE transport: `url`.
    Http,
}

/// Errors from `McpServer` (de)serialisation + validation.
///
/// I/O errors bubble up via `McpError::Io`; serde errors via
/// `McpError::Json`; logic errors have their own variants.
#[derive(Debug, Error)]
pub enum McpError {
    /// `std::fs` error.
    #[error("MCP I/O error: {0}")]
    Io(#[from] std::io::Error),

    /// `serde_json` error.
    #[error("MCP JSON error: {0}")]
    Json(#[from] serde_json::Error),

    /// An entry with the requested `name` already exists in
    /// `mcpServers`. Same deny-policy as F4 (`ProviderError::
    /// AlreadyExists`).
    #[error("MCP server '{0}' already exists")]
    AlreadyExists(String),

    /// The requested `id` was not found in the current list.
    #[error("MCP server with id '{0}' not found")]
    NotFound(String),

    /// `name` is empty, or `transport = stdio` with no `command`,
    /// or `transport = http` with no `url`.
    #[error("MCP server validation failed: {0}")]
    InvalidField(String),
}

impl McpServer {
    /// Build a fresh McpServer with `id = uuid`, `created_at = now`,
    /// `enabled = true`. The service calls this from the F6 "新增"
    /// form. `name` is required; the rest are optional with sensible
    /// defaults.
    pub fn new(
        name: impl Into<String>,
        transport: McpTransport,
        command: Option<String>,
        url: Option<String>,
    ) -> Self {
        Self {
            id: uuid::Uuid::new_v4().to_string(),
            name: name.into(),
            transport,
            command,
            args: Vec::new(),
            env: HashMap::new(),
            url,
            enabled: true,
            created_at: now_unix_secs(),
        }
    }

    /// Read a single `McpServer` from a JSON file.
    ///
    /// Used by tests + the service when reading a *snapshot* of one
    /// server (rare; the service typically reads the whole
    /// `mcp.json`). Kept for symmetry with `Provider::from_json_file`.
    pub fn from_json_file(path: &Path) -> Result<Self, McpError> {
        let bytes = std::fs::read(path)?;
        let s: McpServer = serde_json::from_slice(&bytes)?;
        s.validate()?;
        Ok(s)
    }

    /// Write a single `McpServer` to a JSON file (pretty-printed,
    /// 2-space indent).
    pub fn to_json_file(&self, path: &Path) -> Result<(), McpError> {
        let json = serde_json::to_string_pretty(self)?;
        std::fs::write(path, json)?;
        Ok(())
    }

    /// Validate field invariants. The service calls this after
    /// `from_json`/`serde_json` and before write.
    pub fn validate(&self) -> Result<(), McpError> {
        if self.name.is_empty() {
            return Err(McpError::InvalidField("name must not be empty".into()));
        }
        // id must be a valid slug — this also rejects blank ids.
        if !is_valid_id(&self.id) && !is_uuid_like(&self.id) {
            return Err(McpError::InvalidField(format!(
                "id '{}' must be a UUID",
                self.id
            )));
        }
        match self.transport {
            McpTransport::Stdio => {
                if self.command.as_deref().unwrap_or("").is_empty() {
                    return Err(McpError::InvalidField(
                        "stdio transport requires non-empty command".into(),
                    ));
                }
            }
            McpTransport::Http => {
                if self.url.as_deref().unwrap_or("").is_empty() {
                    return Err(McpError::InvalidField(
                        "http transport requires non-empty url".into(),
                    ));
                }
            }
        }
        Ok(())
    }
}

/// Heuristic: a string looks like a UUID if it has the right
/// shape (8-4-4-4-12 hex digits, separated by `-`). We don't
/// `uuid::Uuid::parse_str` here because the test fixture uses
/// `id: "00000000-0000-0000-0000-000000000000"` style placeholders
/// and we want lenient matching.
///
/// M2.5: this also accepts `Provider`-style slugs (matching
/// `is_valid_id`), so the F3 import path can wire its id through
/// unchanged. The service layer overrides this for the disk
/// representation.
fn is_uuid_like(s: &str) -> bool {
    // 8-4-4-4-12 hex with dashes = 36 chars
    if s.len() != 36 {
        return false;
    }
    let bytes = s.as_bytes();
    for (i, &b) in bytes.iter().enumerate() {
        match i {
            8 | 13 | 18 | 23 => {
                if b != b'-' {
                    return false;
                }
            }
            _ => {
                if !b.is_ascii_hexdigit() {
                    return false;
                }
            }
        }
    }
    true
}

/// Unix seconds — same `std::time::SystemTime` pattern as
/// `Provider::now_unix_secs`. Duplicated locally to keep
/// `domain::mcp_server` self-contained (no cross-module helper
/// dependency).
fn now_unix_secs() -> i64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

// ---------------------------------------------------------------------------
// Tests — TDD coverage for the domain model.
