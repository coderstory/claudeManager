#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    fn sample_stdio() -> McpServer {
        McpServer {
            id: "11111111-2222-3333-4444-555555555555".into(),
            name: "filesystem".into(),
            transport: McpTransport::Stdio,
            command: Some("npx".into()),
            args: vec!["-y".into(), "@mcp/filesystem".into()],
            env: HashMap::from([("ROOT".into(), "/tmp".into())]),
            url: None,
            enabled: true,
            created_at: 1_700_000_000,
        }
    }

    fn sample_http() -> McpServer {
        McpServer {
            id: "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee".into(),
            name: "remote-search".into(),
            transport: McpTransport::Http,
            command: None,
            args: vec![],
            env: HashMap::new(),
            url: Some("https://mcp.example.com/sse".into()),
            enabled: false,
            created_at: 1_700_000_001,
        }
    }

    // ----- construction -----

    #[test]
    fn new_populates_uuid_and_created_at_and_enabled_true() {
        let s = McpServer::new("fs", McpTransport::Stdio, Some("npx".into()), None);
        assert!(is_uuid_like(&s.id), "id should look like a UUID: {}", s.id);
        assert_eq!(s.name, "fs");
        assert!(s.enabled);
        assert!(s.created_at > 1_700_000_000);
        assert!(s.args.is_empty());
        assert!(s.env.is_empty());
        assert!(s.command.is_some());
        assert!(s.url.is_none());
    }

    #[test]
    fn new_for_http_sets_url_and_keeps_command_none() {
        let s = McpServer::new(
            "remote",
            McpTransport::Http,
            None,
            Some("https://x.example/sse".into()),
        );
        assert!(s.url.is_some());
        assert!(s.command.is_none());
    }

    // ----- validation -----

    #[test]
    fn validate_rejects_empty_name() {
        let mut s = sample_stdio();
        s.name = "".into();
        let err = s.validate().unwrap_err();
        assert!(matches!(err, McpError::InvalidField(m) if m.contains("name")));
    }

    #[test]
    fn validate_rejects_stdio_with_no_command() {
        let mut s = sample_stdio();
        s.command = None;
        let err = s.validate().unwrap_err();
        assert!(matches!(err, McpError::InvalidField(m) if m.contains("stdio")));
    }

    #[test]
    fn validate_rejects_http_with_no_url() {
        let mut s = sample_http();
        s.url = None;
        let err = s.validate().unwrap_err();
        assert!(matches!(err, McpError::InvalidField(m) if m.contains("http")));
    }

    #[test]
    fn validate_accepts_valid_stdio() {
        sample_stdio().validate().expect("valid stdio");
    }

    #[test]
    fn validate_accepts_valid_http() {
        sample_http().validate().expect("valid http");
    }

    // ----- roundtrip -----

    #[test]
    fn roundtrip_preserves_all_fields() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("fs.json");
        let original = sample_stdio();
        original.to_json_file(&path).unwrap();
        let restored = McpServer::from_json_file(&path).unwrap();
        assert_eq!(restored, original);
    }

    #[test]
    fn roundtrip_preserves_all_fields_http() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("http.json");
        let original = sample_http();
        original.to_json_file(&path).unwrap();
        let restored = McpServer::from_json_file(&path).unwrap();
        assert_eq!(restored, original);
    }

    // ----- (de)serialisation edge cases -----

    #[test]
    fn serialise_uses_snake_case_field_names() {
        let s = sample_stdio();
        let json = serde_json::to_string_pretty(&s).unwrap();
        assert!(json.contains("\"created_at\""));
        assert!(json.contains("\"enabled\""));
        // command is skipped when None (Option serde option)
        let http = sample_http();
        let json_http = serde_json::to_string_pretty(&http).unwrap();
        assert!(!json_http.contains("\"command\""));
        assert!(json_http.contains("\"url\""));
    }

    #[test]
    fn serialise_transport_uses_lowercase_tag() {
        let s = sample_stdio();
        let v: serde_json::Value = serde_json::to_value(&s).unwrap();
        assert_eq!(v["transport"]["type"], "stdio");
        let h = sample_http();
        let v: serde_json::Value = serde_json::to_value(&h).unwrap();
        assert_eq!(v["transport"]["type"], "http");
    }

    #[test]
    fn deserialise_transport_from_lowercase_tag() {
        let json = r#"{
            "id": "11111111-2222-3333-4444-555555555555",
            "name": "fs",
            "transport": { "type": "stdio" },
            "command": "npx",
            "args": [],
            "env": {},
            "enabled": true,
            "created_at": 1
        }"#;
        let s: McpServer = serde_json::from_str(json).unwrap();
        assert_eq!(s.transport, McpTransport::Stdio);
        assert_eq!(s.command.as_deref(), Some("npx"));
    }

    #[test]
    fn deserialise_with_missing_enabled_defaults_true() {
        let json = r#"{
            "id": "11111111-2222-3333-4444-555555555555",
            "name": "fs",
            "transport": { "type": "stdio" },
            "command": "npx",
            "args": [],
            "env": {},
            "created_at": 1
        }"#;
        let s: McpServer = serde_json::from_str(json).unwrap();
        assert!(s.enabled, "missing `enabled` should default to true");
    }

    #[test]
    fn deserialise_with_missing_args_and_env_defaults_to_empty() {
        let json = r#"{
            "id": "11111111-2222-3333-4444-555555555555",
            "name": "fs",
            "transport": { "type": "stdio" },
            "command": "npx",
            "enabled": true,
            "created_at": 1
        }"#;
        let s: McpServer = serde_json::from_str(json).unwrap();
        assert!(s.args.is_empty());
        assert!(s.env.is_empty());
    }

    #[test]
    fn deserialise_http_with_missing_url_succeeds_validation_will_fail() {
        // Deserialise alone does NOT enforce validation — only
        // from_json_file does. We keep these separate so a partially-
        // populated entry on disk can still be loaded for the UI to
        // show as "incomplete".
        let json = r#"{
            "id": "11111111-2222-3333-4444-555555555555",
            "name": "remote",
            "transport": { "type": "http" },
            "enabled": true,
            "created_at": 1
        }"#;
        let s: McpServer = serde_json::from_str(json).unwrap();
        assert_eq!(s.transport, McpTransport::Http);
        assert!(s.url.is_none());
        // from_json_file runs validate() and would fail.
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("incomplete.json");
        std::fs::write(&path, json).unwrap();
        let err = McpServer::from_json_file(&path).unwrap_err();
        assert!(matches!(err, McpError::InvalidField(_)));
    }

    // ----- from_json_file error paths -----

    #[test]
    fn from_json_file_handles_nonexistent_path() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("does-not-exist.json");
        let err = McpServer::from_json_file(&path).unwrap_err();
        assert!(matches!(err, McpError::Io(_)));
    }

    #[test]
    fn from_json_file_handles_invalid_transport_tag() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("bad.json");
        std::fs::write(
            &path,
            r#"{
                "id": "11111111-2222-3333-4444-555555555555",
                "name": "x",
                "transport": { "type": "websocket" },
                "created_at": 1
            }"#,
        )
        .unwrap();
        let err = McpServer::from_json_file(&path).unwrap_err();
        assert!(matches!(err, McpError::Json(_)));
    }

    #[test]
    fn to_json_file_uses_2_space_indent() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("pretty.json");
        sample_stdio().to_json_file(&path).unwrap();
        let raw = std::fs::read_to_string(&path).unwrap();
        assert!(raw.contains("  \"id\""), "expected 2-space indent:\n{raw}");
    }
}
